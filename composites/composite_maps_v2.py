# ======================================================================================================================
# Composite Analysis of Extreme Precipitation Events (EPEs)
# ======================================================================================================================
#
# DESCRIPTION
# ----------------------------------------------------------------------------------------------------------------------
# This script generates atmospheric composite maps associated with predefined groups of extreme precipitation events
# (EPEs). The composites are calculated from daily standardized anomaly fields and event-date lists previously
# generated by the user.
#
# The workflow includes:
#
#   1. Mean standardized precipitation anomaly + 850 hPa wind vectors
#   2. Mean standardized T850 anomaly + Z500 anomaly contours
#   3. Mean standardized vapor transport anomaly + 850 hPa wind vectors
#
# Composite means are computed only for dates listed in the external CSV file containing the selected EPE events.
#
# The script is fully configurable and intended for reproducible climate diagnostics.
#
# ----------------------------------------------------------------------------------------------------------------------
# REQUIRED INPUT DATA
# ----------------------------------------------------------------------------------------------------------------------
#
# 1. Standardized precipitation dataset
#    Example variable: tp_mm
#
# 2. Wind vector dataset
#    Required variables:
#       - u_component
#       - v_component
#
# 3. Standardized temperature dataset
#    Example variable: t850
#
# 4. Standardized geopotential height dataset
#    Example variable: z500
#
# 5. Standardized vapor transport dataset
#    Example variable: VT_standardized
#
# 6. CSV file containing event dates
#    Required column:
#       - date
#
# ----------------------------------------------------------------------------------------------------------------------
# IMPORTANT USER-DEFINED INPUTS
# ----------------------------------------------------------------------------------------------------------------------
#
# The following variables MUST be configured by the user before execution:
#
#   - group
#       Name of the event group being analysed.
#       Example:
#           group = "Group_01"
#
#   - season
#       Season associated with the selected events.
#       Example:
#           season = "DJF"
#
#   - lag
#       Temporal lag associated with the event selection.
#       Example:
#           lag = "Lag-3"
#
#   - File paths
#       All input and output paths must be adapted to the local machine.
#
# ----------------------------------------------------------------------------------------------------------------------
# OUTPUT
# ----------------------------------------------------------------------------------------------------------------------
#
# The script saves high-resolution figures for each composite analysis:
#
#   - Precipitation anomaly composites
#   - T850 + Z500 composites
#   - Vapor transport composites
#
# ======================================================================================================================
#
# Tested with:
# Python 3.12+ using Spyder IDE
#
