def standardize_longitudes(data_array):
    """
    Convert longitude coordinates from 0–360 to -180–180 if necessary.
    """

    if (data_array.longitude > 180).any():

        data_array = data_array.assign_coords(
            longitude=(((data_array.longitude + 180) % 360) - 180)
        ).sortby("longitude")

    return data_array


def spatial_subset(data_array):
    """
    Select Southern Hemisphere domain.
    """

    return data_array.sel(
        latitude=slice(-90, -20),
        longitude=slice(-180, 0)
    )


def load_event_mask(data_array, event_csv):
    """
    Create a boolean mask based on event dates.
    """

    epe_dates = pd.read_csv(
        event_csv,
        parse_dates=["date"]
    )["date"]

    data_array["time"] = pd.to_datetime(data_array.time.values)

    mask = pd.to_datetime(data_array.time.values).isin(epe_dates)

    if not mask.any():
        raise ValueError(
            "No matching event dates were found."
        )

    return mask


def plot_reference_sites(ax, coordinates_dict):
    """
    Plot reference sites on the map.
    """

    for label, (lat, lon) in coordinates_dict.items():

        ax.plot(
            lon,
            lat,
            marker="*",
            color="red",
            markersize=2,
            transform=ccrs.PlateCarree(),
            zorder=11
        )


def add_mask_patches(ax):
    """
    Add white mask patches to hide unwanted map regions.
    """

    ax.add_patch(
        plt.Rectangle(
            xy=(-180, -16.0),
            width=180,
            height=16.5,
            transform=ccrs.PlateCarree(),
            facecolor="white",
            edgecolor="none",
            zorder=10
        )
    )

    ax.add_patch(
        plt.Rectangle(
            xy=(5.0, -60),
            width=170,
            height=71.0,
            transform=ccrs.PlateCarree(),
            facecolor="white",
            edgecolor="none",
            zorder=10
        )
    )


def initialize_map():
    """
    Create map projection and basic figure layout.
    """

    fig, ax = plt.subplots(
        figsize=(5, 3),
        subplot_kw={
            "projection": ccrs.Orthographic(
                central_longitude=-90,
                central_latitude=-60
            )
        }
    )

    ax.spines["geo"].set_visible(False)

    ax.set_extent(
        [-180, 0, -90, -20],
        crs=ccrs.PlateCarree()
    )

    ax.coastlines()

    ax.add_feature(
        cfeature.BORDERS,
        linewidth=0.3
    )

    ax.gridlines(
        draw_labels=False,
        linewidth=0.3
    )

    return fig, ax


